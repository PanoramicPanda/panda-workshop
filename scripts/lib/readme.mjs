import { SITE_URL, projectUrl } from './paths.mjs';

export const START_MARKER = '<!-- PROJECTS:START — generated by scripts/update-readme.mjs; do not edit by hand -->';
export const END_MARKER = '<!-- PROJECTS:END -->';
const START_RE = /<!-- PROJECTS:START[^>]*-->/;

const escapeMd = (s) => String(s).replace(/([\\`*_[\]<>|])/g, '\\$1');

/** Markdown for the generated "Projects" block (hidden projects excluded). */
export function renderReadmeBlock(projects) {
  const visible = projects
    .filter((p) => !p.hidden)
    .sort((a, b) => Number(b.featured) - Number(a.featured) || a.name.localeCompare(b.name));

  if (visible.length === 0) {
    return '_No projects published yet. Add a folder with an `index.html` to `projects/` to get started._';
  }

  return visible
    .map((p) => {
      const lines = [`### ${escapeMd(p.name)}${p.featured ? ' ⭐' : ''}`, '', escapeMd(p.description), ''];
      lines.push(`- **Live:** <${SITE_URL}${projectUrl(p.slug)}>`);
      lines.push(`- **Source:** [\`projects/${p.slug}/\`](projects/${p.slug}/)`);
      lines.push(`- **Category:** ${escapeMd(p.category)}`);
      lines.push(`- **Type:** ${p.mode === 'build' ? 'Built app (Vite + React)' : 'Static HTML'}`);
      if (p.tags.length) lines.push(`- **Tags:** ${p.tags.map((t) => `\`${t.replace(/`/g, '')}\``).join(', ')}`);
      return lines.join('\n');
    })
    .join('\n\n');
}

/**
 * Replaces everything between the markers with `block`.
 * If the markers are missing, appends a "Projects" section at the end.
 */
export function updateReadmeText(text, block) {
  const content = `${START_MARKER}\n\n${block}\n\n${END_MARKER}`;
  const start = text.search(START_RE);
  const end = text.indexOf(END_MARKER);
  let next;
  if (start !== -1 && end > start) {
    next = text.slice(0, start) + content + text.slice(end + END_MARKER.length);
  } else {
    next = `${text.replace(/\s*$/, '')}\n\n## Projects\n\n${content}\n`;
  }
  return { text: next, changed: next !== text };
}
